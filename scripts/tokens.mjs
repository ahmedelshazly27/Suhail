// Regenerates design-system/tokens.json and emails/theme.ts from design-system/tokens.css.
// tokens.css is the only file anyone edits by hand.
import fs from "node:fs";

const css = fs.readFileSync("design-system/tokens.css", "utf8");
const block = (re) => (css.match(re) || [, ""])[1];
const vars = (src) => Object.fromEntries([...src.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)].map(([, k, v]) => [k, v.trim()]));

const prev = JSON.parse(fs.readFileSync("design-system/tokens.json", "utf8"));
const out = {
  light: vars(block(/:root\{([\s\S]*?)\n\}/)),
  dark: vars(block(/:root\[data-theme="dark"\](?:, \[data-theme="dark"\])?\{([\s\S]*?)\}/)),
  arabic: vars(block(/:root\[lang="ar"\](?:, \[lang="ar"\])?\{([\s\S]*?)\}/)),
  fonts: prev.fonts,
  breakpoints: prev.breakpoints,
};
fs.writeFileSync("design-system/tokens.json", JSON.stringify(out, null, 2) + "\n");

// Email clients don't load web fonts or CSS variables, so emails get resolved values.
fs.mkdirSync("emails", { recursive: true });
fs.writeFileSync("emails/theme.ts", `// Generated by scripts/tokens.mjs from design-system/tokens.json. Do not edit.
import tokens from "../design-system/tokens.json";

export const theme = {
  bg: tokens.light.bg,
  fg: tokens.light.fg,
  muted: tokens.light.muted,
  line: tokens.light.line,
  soft: tokens.light.soft,
  accent: tokens.light.accent,
  display: tokens.light["f-email-display"],
  displayAr: tokens.light["f-email-display-ar"],
  body: tokens.light["f-email-body"],
  width: 560,
} as const;
`);
console.log("tokens.json and emails/theme.ts written");
